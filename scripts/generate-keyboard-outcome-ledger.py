#!/usr/bin/env python3
"""Join the generated registry to frozen, explicitly scoped native outcome witnesses.

This never derives action correctness from routing, shortcut registration or a source grep.
Additional witnesses are curated assertions backed by a successful native harness report.
"""
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parents[1]
evidence = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "docs/evidence/key04-effects-2026-11-17"
commands = re.findall(r"^\| `([^`]+)`", (root / "docs/keyboard-command-inventory.md").read_text(), re.M)
witnesses = defaultdict(list)
successful_effects = set()
for file in sorted((evidence / "outcomes").glob("*.tsv")):
    for row in csv.DictReader(file.open(), delimiter="\t"):
        witnesses[row["command"]].append((str(file.relative_to(evidence)), row["assertion"]))
extra = evidence / "additional-witnesses.json"
if extra.exists():
    for witness in json.loads(extra.read_text()):
        report = evidence / witness["report"]
        if witness["required_text"] not in report.read_text():
            raise SystemExit(f"Missing success assertion in {report}: {witness['required_text']}")
        for command in witness["commands"]:
            witnesses[command].append((witness["report"], witness["scope"]))
            # Explicitly qualified positive branches require the success assertion above.
            # Older cancellation/guard evidence remains visible without controlling the new result.
            if witness.get("successful_effect") is True:
                successful_effects.add(command)
unknown = set(witnesses) - set(commands)
if unknown:
    raise SystemExit(f"Witnesses refer to unknown registry IDs: {sorted(unknown)}")

branch_only = {"ai.cloud", "ai.local", "ai.download", "project.sources", "project.javadoc", "project.parentPom"}
lines = ["# Native command outcome ledger", "",
         "Generated by `scripts/generate-keyboard-outcome-ledger.py` from the generated registry and frozen outcome assertions.",
         "**A witnessed case is not exhaustive proof of every input or nested-dialog branch.** Read the precise scope in each row.",
         "`WITNESSED` means an asserted callback effect; `BRANCH ONLY` means a guard/configuration/cancellation case without the successful external operation; `UNVERIFIED` has no effect witness in this run.",
         "Physical keyboard/IME/VoiceOver validation is excluded. Source/fixture setup may be programmatic; native keyboard controls and their effects are tested.", "",
         "| Command | Evidence status | Asserted effect / limitation |", "| --- | --- | --- |"]
counts = defaultdict(int)
for command in commands:
    entries = list(dict.fromkeys(witnesses[command]))
    state = "BRANCH ONLY" if entries and command in branch_only and command not in successful_effects else "WITNESSED" if entries else "UNVERIFIED"
    counts[state] += 1
    details = "<br>".join(f"[{scope.replace('|', '&#124;')}]({report})" for report, scope in entries)
    lines.append(f"| `{command}` | {state} | {details or 'No callback-outcome witness recorded; routing alone does not establish the result.'} |")
lines[7:7] = [f"{len(commands)} registered commands: " + ", ".join(f"{n} {s.lower()}" for s, n in sorted(counts.items())) + ".", ""]
(evidence / "command-outcomes.md").write_text("\n".join(lines) + "\n")
print(dict(counts))
