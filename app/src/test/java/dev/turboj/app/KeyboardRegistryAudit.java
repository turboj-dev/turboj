package dev.turboj.app;

import dev.turboj.commandj.core.*;
import dev.turboj.commandj.keymap.*;
import dev.turboj.config.Settings;
import java.nio.file.*;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.*;
import java.util.concurrent.FutureTask;
import javax.swing.*;

/** Generates documentation from the actual application registry, never a parallel action list. */
public final class KeyboardRegistryAudit {
    public static void main(String[] args) throws Exception {
        Path output = Path.of(args.length == 0 ? "app/target/keyboard-audit" : args[0]).toAbsolutePath();
        Files.createDirectories(output);
        System.setProperty("turboj.config", Files.createTempDirectory("turboj-keyboard-inventory-").toString());
        var task = new FutureTask<Void>(() -> {
            Settings words = new Settings(); words.shortcutSymbols = false; // Generated docs spell shortcuts out.
            TurboFrame frame = new TurboFrame(words, Map.of());
            try {
                var registry = frame.commandRegistry();
                var maps = frame.commandKeymaps();
                StringBuilder inventory = new StringBuilder("# Keyboard command inventory\n\n")
                        .append("Generated by `KeyboardRegistryAudit` from a real `TurboFrame` and CommandJ's bundled profiles.\n")
                        .append("Do not edit this table manually. Unassigned actions remain discoverable in the Command Palette.\n")
                        .append("Status describes registration and availability in an editable Java buffer, not proof of every language case.\n")
                        .append("The Test column identifies the relevant suite; actual execution and limits are in `keyboard-accessibility-audit.md`.\n\n")
                        .append("| Command ID | Category | IntelliJ | Eclipse | VS Code | TurboJ | Status | Test |\n")
                        .append("| --- | --- | --- | --- | --- | --- | --- | --- |\n");
                List<String> profiles = List.of("intellij-macos", "eclipse-macos", "vscode-macos", "turboj-macos");
                var context = CommandContext.of("workspace", "editor", "editable");
                for (Command command : registry.commands().stream().sorted(Comparator.comparing(Command::id)).toList()) {
                    inventory.append("| `").append(command.id()).append("` | ").append(cell(command.category())).append(" |");
                    for (String profile : profiles) {
                        var bindings = ShortcutReference.bindings(registry, maps.bindingsForProfile(profile), command.id());
                        inventory.append(' ').append(bindings.isEmpty() ? "Unassigned" : cell(String.join(" / ", bindings.stream()
                                .map(binding -> binding.sequence().display()).toList()))).append(" |");
                    }
                    var available = command.available(context);
                    inventory.append(" Implemented; ").append(available.enabled() ? "available" : cell(available.reason()))
                            .append(" | ").append(suite(command)).append(" |\n");
                }
                inventory.append("\n## Preserved command-ID aliases\n\n");
                registry.aliases().entrySet().stream().sorted(Map.Entry.comparingByKey()).forEach(entry ->
                        inventory.append("- `").append(entry.getKey()).append("` → `").append(entry.getValue()).append("`\n"));
                Files.writeString(output.resolve("keyboard-command-inventory.md"), inventory);
                Files.writeString(output.resolve("keyboard-shortcut-reference.md"), ShortcutReference.markdown(registry, maps, context));
                StringBuilder conflicts = new StringBuilder("# Generated keyboard conflict audit\n\n");
                int unreachable = 0;
                for (String profile : profiles) {
                    maps.select(profile); conflicts.append("## ").append(profile).append("\n\n");
                    var diagnostics = ShortcutReference.audit(registry, maps);
                    if (diagnostics.isEmpty()) conflicts.append("No conflicts or reserved-key diagnostics.\n\n");
                    else for (String diagnostic : diagnostics) conflicts.append("- ").append(diagnostic).append('\n');
                    for (var entry : maps.bindings().entrySet()) if (!entry.getValue().isEmpty() && registry.find(entry.getKey()).isEmpty()) unreachable++;
                    conflicts.append('\n');
                }
                Files.writeString(output.resolve("keyboard-conflicts.md"), conflicts);
                var sourceHashes = new TreeMap<String, String>();
                for (String root : List.of("app/src/main/java", "commandj", "refactorj/refactorj-api/src/main/java")) {
                    try (var files = Files.walk(Path.of(root))) {
                        for (Path source : files.filter(Files::isRegularFile).filter(path -> path.toString().endsWith(".java")
                                && path.toString().contains("/src/main/java/")).sorted().toList())
                            sourceHashes.put(source.toString().replace('\\', '/'), digest(Files.readAllBytes(source)));
                    }
                }
                String generator = "app/src/test/java/dev/turboj/app/KeyboardRegistryAudit.java";
                sourceHashes.put(generator, digest(Files.readAllBytes(Path.of(generator))));
                var generatedHashes = new TreeMap<String, String>();
                for (String name : List.of("keyboard-command-inventory.md", "keyboard-shortcut-reference.md", "keyboard-conflicts.md"))
                    generatedHashes.put(Path.of("").toAbsolutePath().relativize(output.resolve(name)).toString().replace('\\', '/'),
                            digest(Files.readAllBytes(output.resolve(name))));
                String manifest = new com.google.gson.GsonBuilder().setPrettyPrinting().create().toJson(Map.of(
                        "schema", 1, "files", sourceHashes, "generatedfiles", generatedHashes,
                        "generatedAt", java.time.Instant.now().toString(), "commands", registry.commands().size(),
                        "aliases", registry.aliases().size(), "artifactSha256", digest(Files.readAllBytes(Path.of(
                                TurboFrame.class.getProtectionDomain().getCodeSource().getLocation().toURI())))));
                Files.writeString(output.resolve("keyboard-reference-sources.json"), manifest + "\n", StandardCharsets.UTF_8);
                System.out.println("Registered commands: " + registry.commands().size() + "; aliases: " + registry.aliases().size()
                        + "; bindings without a callback: " + unreachable);
                if (unreachable != 0) throw new AssertionError("Unreachable bundled shortcuts: " + unreachable);
            } finally { frame.shutdown(); frame.dispose(); }
            return null;
        });
        SwingUtilities.invokeAndWait(task);
        task.get();
    }
    private static String cell(String text) { return text.replace("|", "\\|").replace('\n', ' '); }
    private static String digest(byte[] bytes) throws Exception { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)); }
    private static String suite(Command command) {
        String id = command.id();
        if (Set.of("workspace.select", "file.newJavaProject", "file.newMavenProject", "file.newJavaClass", "refactor.context-actions").contains(id))
            return "FirstLaunchKeyboardSmoke / FirstLaunchProjectsTest / QuickActionsIT; see first-launch-keyboard-acceptance.md";
        if (id.startsWith("keymap.profile.")) return "ProfileSwitchTest / KeyboardProfileSmoke";
        if (command.category().equals("Java Structure")) return "KeyboardJavaIT / KeyboardWorkflowSmoke";
        if (id.startsWith("editor.") || Set.of("cut", "copy", "paste", "duplicateLine", "deleteLine", "moveLineUp", "moveLineDown", "comment", "indent", "unindent", "undo", "redo").contains(id))
            return "KeyboardEditingTest / KeyboardWorkflowSmoke";
        return "KeyboardWorkflowSmoke + existing controller suites; see audit";
    }
}
