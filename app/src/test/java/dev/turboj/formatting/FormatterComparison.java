package dev.turboj.formatting;

import com.sun.source.tree.LiteralTree;
import com.sun.source.util.JavacTask;
import com.sun.source.util.TreeScanner;
import dev.javafmt.core.FormatRequest;
import dev.javafmt.core.FormatResult;
import dev.javafmt.core.LineEndingPolicy;
import java.io.StringWriter;
import java.net.URI;
import java.nio.file.*;
import java.util.*;
import javax.tools.*;

/**
 * Formats the corpus in docs/formatting/corpus with the four google-java-format presets and writes
 * docs/formatting-comparison.md: every output comes from the engine, unedited, with the checks that matter for TurboJ
 * (idempotence, compilation, literals, comments, imports) and measured timings. Run: FormatterComparison [repo root].
 */
public final class FormatterComparison {
    static final List<StandardFormatters> PRESETS = List.of(StandardFormatters.CLASSIC_80, StandardFormatters.AOSP,
            StandardFormatters.WIDE_120, StandardFormatters.GOOGLE);
    /** Spring's annotations are not on this classpath: that example is formatted and checked, but not compiled. */
    static final Set<String> NOT_COMPILED = Set.of("04_OrderController.java");

    record Check(String preset, String example, int lines, int widest, long overWidth, boolean idempotent, String compiles,
            boolean literals, boolean comments, boolean imports) {}

    public static void main(String[] args) throws Exception {
        Path root = Path.of(args.length > 0 ? args[0] : ".").toAbsolutePath().normalize();
        Path corpus = root.resolve("docs/formatting/corpus");
        var files = new ArrayList<Path>();
        try (var listing = Files.list(corpus)) { listing.filter(p -> p.toString().endsWith(".java")).sorted().forEach(files::add); }

        var timings = timings(root, files.getFirst());
        var out = new StringBuilder();
        var checks = new ArrayList<Check>();
        out.append("# Formatter comparison: google-java-format presets\n\n")
                .append("Generated by `FormatterComparison` from `docs/formatting/corpus` with google-java-format ")
                .append(StandardFormatters.GOOGLE_JAVA_FORMAT_VERSION).append(" (Java API, in process), JDK ")
                .append(Runtime.version()).append(". Every output below is the engine's, unedited.\n\n")
                .append("| Preset | Engine style | Indent | Width | Kind |\n| --- | --- | --- | --- | --- |\n");
        for (var preset : PRESETS) {
            var options = preset.googleOptions();
            out.append("| ").append(preset.title()).append(" | ").append(options.style().isAosp() ? "AOSP" : "Google").append(" | ")
                    .append(options.style().indentationMultiplier() * 2).append(" spaces | ").append(options.maxLineLength())
                    .append(" | ").append(preset == StandardFormatters.AOSP || preset == StandardFormatters.GOOGLE ? "engine style" : "TurboJ preset")
                    .append(" |\n");
        }
        out.append("\nAll presets: `formatJavadoc(false)`, `reorderModifiers(false)`, `Formatter.formatSource`, which neither sorts")
                .append(" nor removes imports and does not split long strings.\n\n");

        var sections = new StringBuilder();
        for (Path file : files) {
            String name = file.getFileName().toString();
            String source = Files.readString(file);
            if (!NOT_COMPILED.contains(name) && !compile(name, source).equals("yes"))
                throw new IllegalStateException("Corpus input does not compile: " + name + ": " + compile(name, source));
            sections.append("## ").append(name).append("\n\nInput, as typed:\n\n```java\n").append(source.stripTrailing()).append("\n```\n\n");
            for (var preset : PRESETS) {
                var engine = preset.engine();
                FormatResult result = engine.format(new FormatRequest(source, 1, LineEndingPolicy.PRESERVE), null, "25");
                if (!result.success()) {
                    sections.append("### ").append(preset.title()).append("\n\nNot formatted: ").append(result.diagnostics().getFirst().message()).append("\n\n");
                    checks.add(new Check(preset.title(), name, 0, 0, 0, false, "—", false, false, false));
                    continue;
                }
                String formatted = result.formattedText();
                String twice = engine.format(new FormatRequest(formatted, 2, LineEndingPolicy.PRESERVE), null, "25").formattedText();
                int width = preset.width();
                var lines = formatted.lines().toList();
                int widest = lines.stream().mapToInt(String::length).max().orElse(0);
                long over = lines.stream().filter(line -> line.length() > width).count();
                String compiles = NOT_COMPILED.contains(name) ? "not compiled (Spring)" : compile(name, formatted);
                var check = new Check(preset.title(), name, lines.size(), widest, over, formatted.equals(twice), compiles,
                        literals(source).equals(literals(formatted)), comments(source).equals(comments(formatted)),
                        imports(source).equals(imports(formatted)));
                checks.add(check);
                sections.append("### ").append(preset.title()).append(" · ").append(lines.size()).append(" lines, widest ")
                        .append(widest).append(over > 0 ? ", " + over + " over " + width : "").append("\n\n```java\n")
                        .append(formatted.stripTrailing()).append("\n```\n\n");
            }
        }

        out.append("## Summary\n\n| Example | ");
        for (var preset : PRESETS) out.append(preset.title()).append(" | ");
        out.append("\n| --- |").append(" --- |".repeat(PRESETS.size())).append("\n");
        for (Path file : files) {
            String name = file.getFileName().toString();
            out.append("| ").append(name).append(" | ");
            for (var preset : PRESETS) checks.stream().filter(c -> c.example().equals(name) && c.preset().equals(preset.title())).findFirst()
                    .ifPresent(c -> out.append(c.lines()).append(" lines · widest ").append(c.widest()).append(c.overWidth() > 0 ? " · " + c.overWidth() + " over" : "").append(" | "));
            out.append("\n");
        }
        out.append("\n| Check (all presets × all examples) | Result |\n| --- | --- |\n")
                .append("| Idempotent: formatting the output again changes nothing | ").append(tally(checks, Check::idempotent)).append(" |\n")
                .append("| Output compiles with `javac --release 25` | ").append(checks.stream().filter(c -> c.compiles().equals("yes")).count())
                .append(" of ").append(checks.stream().filter(c -> !c.compiles().startsWith("not")).count()).append(" compiled")
                .append(checks.stream().filter(c -> !c.compiles().equals("yes") && !c.compiles().startsWith("not")).map(c -> "; " + c.preset() + " " + c.example() + ": " + c.compiles()).reduce("", String::concat))
                .append(" |\n")
                .append("| String and text block values unchanged (javac literal values) | ").append(tally(checks, Check::literals)).append(" |\n")
                .append("| Comment text unchanged (ignoring indentation) | ").append(tally(checks, Check::comments)).append(" |\n")
                .append("| Import lines unchanged and in order | ").append(tally(checks, Check::imports)).append(" |\n\n");
        out.append(timings).append(sections);
        Files.writeString(root.resolve("docs/formatting-comparison.md"), out.toString());
        System.out.println("Wrote " + root.resolve("docs/formatting-comparison.md") + " · " + checks.size() + " outputs");
    }

    private static String tally(List<Check> checks, java.util.function.Predicate<Check> test) {
        long passed = checks.stream().filter(test).count();
        return passed + " of " + checks.size() + (passed == checks.size() ? "" : " — " + checks.stream().filter(test.negate())
                .map(c -> c.preset() + " " + c.example()).toList());
    }

    /** First request in this JVM, then a fresh engine's first request and the median of ten more, per file size. */
    private static String timings(Path root, Path small) throws Exception {
        var sizes = new LinkedHashMap<String, String>();
        sizes.put("small (" + small.getFileName() + ")", Files.readString(small));
        sizes.put("medium (StandardFormatters.java copy)", Files.readString(root.resolve("app/src/main/java/dev/turboj/formatting/StandardFormatters.java")));
        sizes.put("large (TurboFrame.java copy)", Files.readString(root.resolve("app/src/main/java/dev/turboj/app/TurboFrame.java")));
        long cold = System.nanoTime();
        StandardFormatters.AOSP.engine().format(new FormatRequest(sizes.values().iterator().next(), 0, LineEndingPolicy.PRESERVE), null, "25");
        cold = System.nanoTime() - cold;
        var out = new StringBuilder("## Timings (measured on this machine)\n\nFirst request in a fresh JVM (loads google-java-format and javac's parser): **")
                .append(ms(cold)).append("**.\n\n| File | Lines | Preset | First request, new engine | Next requests, median of 10 |\n| --- | --- | --- | --- | --- |\n");
        for (var size : sizes.entrySet()) {
            for (var preset : List.of(StandardFormatters.AOSP, StandardFormatters.CLASSIC_80)) {
                var engine = preset.engine();
                long first = System.nanoTime();
                engine.format(new FormatRequest(size.getValue(), 0, LineEndingPolicy.PRESERVE), null, "25");
                first = System.nanoTime() - first;
                long[] next = new long[10];
                for (int i = 0; i < next.length; i++) {
                    long start = System.nanoTime();
                    engine.format(new FormatRequest(size.getValue(), i, LineEndingPolicy.PRESERVE), null, "25");
                    next[i] = System.nanoTime() - start;
                }
                Arrays.sort(next);
                out.append("| ").append(size.getKey()).append(" | ").append(size.getValue().lines().count()).append(" | ").append(preset.title())
                        .append(" | ").append(ms(first)).append(" | ").append(ms(next[next.length / 2])).append(" |\n");
            }
        }
        return out.append("\n").toString();
    }

    private static String ms(long nanos) { return String.format(Locale.ROOT, "%.1f ms", nanos / 1e6); }

    /** "yes", or javac's first error. */
    static String compile(String fileName, String source) throws Exception {
        String className = fileName.replaceFirst("^\\d+_", "");
        var compiler = ToolProvider.getSystemJavaCompiler();
        Path out = Files.createTempDirectory("formatter-comparison-");
        var diagnostics = new DiagnosticCollector<JavaFileObject>();
        var file = new SimpleJavaFileObject(URI.create("string:///" + className), JavaFileObject.Kind.SOURCE) {
            @Override public CharSequence getCharContent(boolean ignore) { return source; }
        };
        boolean ok = compiler.getTask(new StringWriter(), null, diagnostics, List.of("--release", "25", "-proc:none", "-d", out.toString()),
                null, List.of(file)).call();
        if (ok) return "yes";
        return diagnostics.getDiagnostics().stream().filter(d -> d.getKind() == Diagnostic.Kind.ERROR).findFirst()
                .map(d -> "line " + d.getLineNumber() + ": " + d.getMessage(Locale.ROOT)).orElse("failed");
    }

    /** The values of every string, char and text block literal, in order, as javac reads them. */
    static List<Object> literals(String source) throws Exception {
        var compiler = ToolProvider.getSystemJavaCompiler();
        var file = new SimpleJavaFileObject(URI.create("string:///Literals.java"), JavaFileObject.Kind.SOURCE) {
            @Override public CharSequence getCharContent(boolean ignore) { return source; }
        };
        var task = (JavacTask) compiler.getTask(new StringWriter(), null, d -> {}, List.of("--release", "25", "-proc:none"), null, List.of(file));
        var values = new ArrayList<Object>();
        for (var unit : task.parse()) unit.accept(new TreeScanner<Void, Void>() {
            @Override public Void visitLiteral(LiteralTree node, Void ignored) {
                if (node.getValue() instanceof String || node.getValue() instanceof Character) values.add(node.getValue());
                return null;
            }
        }, null);
        return values;
    }

    /** Every comment's text, in order, with each line's leading whitespace removed (the formatter re-indents comments). */
    static List<String> comments(String source) {
        var comments = new ArrayList<String>();
        for (int i = 0; i < source.length(); i++) {
            char c = source.charAt(i);
            if (source.startsWith("\"\"\"", i)) { int end = source.indexOf("\"\"\"", i + 3); while (end > 0 && source.charAt(end - 1) == '\\') end = source.indexOf("\"\"\"", end + 1); i = end < 0 ? source.length() : end + 2; }
            else if (c == '"' || c == '\'') { int j = i + 1; while (j < source.length() && source.charAt(j) != c) j += source.charAt(j) == '\\' ? 2 : 1; i = j; }
            else if (source.startsWith("//", i)) { int end = source.indexOf('\n', i); end = end < 0 ? source.length() : end; comments.add(source.substring(i, end).strip()); i = end; }
            else if (source.startsWith("/*", i)) {
                int end = source.indexOf("*/", i + 2); end = end < 0 ? source.length() : end + 2;
                comments.add(String.join("\n", source.substring(i, end).lines().map(String::strip).toList())); i = end - 1;
            }
        }
        return comments;
    }

    static List<String> imports(String source) {
        return source.lines().map(String::strip).filter(line -> line.startsWith("import ")).toList();
    }
}
