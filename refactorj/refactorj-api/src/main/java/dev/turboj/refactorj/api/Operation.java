package dev.turboj.refactorj.api;

import java.util.Locale;

/** Operation identifiers do not imply availability; ask the engine for applicable descriptors. */
public enum Operation {
    RENAME, EXTRACT_METHOD, EXTRACT_VARIABLE, EXTRACT_CONSTANT, EXTRACT_FIELD, EXTRACT_PARAMETER,
    INLINE_VARIABLE, INLINE_METHOD, CHANGE_SIGNATURE, MOVE, SAFE_DELETE, EXTRACT_INTERFACE,
    INTRODUCE_INTERFACE, PULL_UP, PUSH_DOWN, ENCAPSULATE_FIELD, CONSTRUCTOR_TO_FACTORY,
    ANONYMOUS_TO_LAMBDA, LAMBDA_TO_METHOD_REFERENCE, METHOD_REFERENCE_TO_LAMBDA,
    SWITCH_TO_EXPRESSION, TYPE_TO_VAR, VAR_TO_TYPE, ORGANIZE_IMPORTS,
    ADD_IMPORT, REMOVE_IMPORT, IMPLEMENT_METHODS, CREATE_METHOD, CREATE_CONSTRUCTOR,
    CREATE_FIELD, CREATE_LOCAL, FIX_TYPE_MISMATCH, REMOVE_UNREACHABLE;
    public String id() { return name().toLowerCase(Locale.ROOT).replace('_', '-'); }
}
